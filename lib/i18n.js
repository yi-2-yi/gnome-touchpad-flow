export function getTranslations(lang) {
    return TRANSLATIONS[lang] ?? TRANSLATIONS.en;
}

export function getLocalizedErrorMessage(lang, code, fallbackMsg = '') {
    const t = getTranslations(lang);
    switch (code) {
        case 'NO_PERMISSION':
            return t.err_no_permission;
        case 'NO_TOUCHPAD':
            return t.err_no_touchpad;
        case 'NO_BACKEND':
        case 'NO_LIBINPUT':
            return t.err_no_backend;
        case 'BRIDGE_CRASHED':
            return t.err_bridge_crashed;
        default:
            return fallbackMsg || code || 'Error';
    }
}
